"""Pull Naturbase NiN naturtyper for Kristiansand and build the sensitive set.

    python scripts/fetch_naturbase.py

This is the layer that lets the suppression step in `scripts/build_maps.py`
actually screen something. Until it ran, every exported map carried the notice
"SUPPRESSION RAN WITH AN EMPTY SENSITIVE SET ... this raster is NOT screened".
"""
from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

import yaml

from src.geometry import Boundary
from src.ingest import naturbase

ROOT = pathlib.Path(__file__).resolve().parents[1]
INTERIM = ROOT / "data" / "interim"
OUT_JSON = INTERIM / "naturbase_kristiansand_25833.geojson"
OUT_MD = ROOT / "data" / "processed" / "naturbase.md"

# The map window plus a margin: a sensitive polygon just outside the kommune
# still needs suppressing, because the blur radius reaches across the boundary.
MARGIN_M = 2000.0


def main() -> int:
    area = yaml.safe_load((ROOT / "config" / "study_area.yaml").read_text(encoding="utf-8"))
    cfg = area["prediction_extent"]
    fc = json.loads((ROOT / cfg["boundary_file"]).read_text(encoding="utf-8"))
    b = Boundary(fc["features"][0]["geometry"], name=cfg["name"])
    minx, miny, maxx, maxy = b.bbox
    bbox = (minx - MARGIN_M, miny - MARGIN_M, maxx + MARGIN_M, maxy + MARGIN_M)

    expected = naturbase.count(bbox)
    print(f"{expected:,} naturtype polygons intersect the window; fetching ...",
          flush=True)
    feats = naturbase.fetch(bbox)
    print(f"fetched {len(feats):,}", flush=True)
    if len(feats) < expected:
        # A short read shrinks the sensitive set, and this layer failing quiet
        # is precisely the failure that matters. Stop rather than under-screen.
        raise SystemExit(
            f"SHORT READ: expected {expected}, got {len(feats)}. Refusing to "
            "build a sensitive set that may be missing localities."
        )

    naturbase.save(feats, OUT_JSON)
    polys, summary = naturbase.sensitive_polygons(feats)

    lines = []
    a = lines.append
    a("# Naturbase NiN naturtyper - the red-list suppression set\n")
    a("Generated by `scripts/fetch_naturbase.py`. Not a model feature and never "
      "becomes one.\n")
    a(f"`{OUT_JSON.relative_to(ROOT)}` - {len(feats):,} polygons over "
      f"{cfg['name']} plus a {MARGIN_M:.0f} m margin, EPSG:25833.\n")
    a("CLAUDE.md requires the suppression capability in the tile pipeline from "
      "the start, not as a later policy layer. This is what it screens "
      "against. The argument for it is that a habitat suitability map is *most* "
      "accurate exactly where publishing it does most harm: the terrain that "
      "scores well for an interesting fungus is the terrain that shelters "
      "threatened ones.\n")

    a("## What counts as sensitive\n")
    a("The rule lives in `src/ingest/naturbase.py:is_sensitive` so it is one "
      "decision in one place. It is deliberately over-inclusive - suppressing "
      "an ordinary patch costs a slightly blurrier map, failing to suppress a "
      "threatened one costs the habitat. Any one trigger is enough:\n")
    a("* `UK_Truet` - Miljodirektoratet's own threatened-habitat-type flag")
    a("* `Lokalitetskvalitet >= 3` on a 0-4 scale")
    a("* `Naturmangfold >= 2` on a 0-2 scale\n")
    a(f"**{summary['sensitive']:,} of {len(feats):,} polygons are sensitive** "
      f"({100.0 * summary['sensitive'] / max(len(feats), 1):.1f}%), giving "
      f"{summary['rings']:,} rings to suppress around.\n")
    a("| trigger | polygons |")
    a("|---|---|")
    for reason, n in sorted(summary["reasons"].items(), key=lambda kv: -kv[1]):
        a(f"| {reason} | {n:,} |")
    a("")

    a("## What this does not cover\n")
    a("Most of Agder has never been surveyed for naturtyper. These polygons "
      "are where somebody looked, not where the sensitive habitat is. The "
      "unmapped ground is the far larger gap, and suppression cannot close "
      "it - it can only handle what Miljodirektoratet has recorded.\n")
    a("Localities the survey left unscored are treated as not sensitive. That "
      "is a gap rather than a judgement: unscored means nobody assessed it.\n")
    a("Neither mode is a security control. Both assume the sensitive polygons "
      "themselves are not published next to the suppressed map - and Naturbase "
      "is public, so a determined reader can recover the locations from the "
      "source regardless. Suppression raises the effort, it does not prevent.\n")

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"written: {OUT_JSON.relative_to(ROOT)}")
    print(f"written: {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
