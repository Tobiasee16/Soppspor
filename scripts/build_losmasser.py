"""Burn NGU superficial deposits onto the Agder terrain grid.

    python scripts/build_losmasser.py

Reads the shapefile downloaded by `scripts/download_rasters.py`, collapses the
30 `jordart` codes present in Agder into the ten depositional groups fixed in
`src/ingest/losmasser.py`, and writes a uint8 raster aligned cell-for-cell with
`data/interim/terrain_agder_32m.tif`.

The grouping is frozen before fitting and the prediction for what this layer
will do is registered in FINDINGS section 8. This script does not choose
anything; it reports coverage so a reader can see how much of the extent the
layer actually answers for.
"""
from __future__ import annotations

import pathlib
import sys
import zipfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

from src.ingest.losmasser import LABELS, rasterise

ROOT = pathlib.Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "losmasser"
INTERIM = ROOT / "data" / "interim"
EXTRACT = INTERIM / "losmasser"
REFERENCE = INTERIM / "terrain_agder_32m.tif"
OUT_TIF = INTERIM / "losmasser_agder_32m.tif"
OUT_MD = ROOT / "data" / "processed" / "losmasser.md"

ZIP_NAME = "Geologi_42_Agder_25833_Losmasser_SHAPE.zip"
SHAPE_STEM = "Losmasse/LosmasseFlate_20240621"


def extract() -> pathlib.Path:
    """Unpack just the polygon layer. The boundary-line layer is 116 MB and unused."""
    shp = EXTRACT / f"{SHAPE_STEM}.shp"
    if shp.exists():
        return shp
    archive = RAW / ZIP_NAME
    if not archive.exists():
        raise SystemExit(f"missing {archive} - run scripts/download_rasters.py --only losmasser")
    EXTRACT.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive) as z:
        for member in z.namelist():
            if member.startswith(f"{SHAPE_STEM.split('/')[0]}/LosmasseFlate"):
                z.extract(member, EXTRACT)
    if not shp.exists():
        raise SystemExit(f"{ZIP_NAME} did not contain {SHAPE_STEM}.shp")
    return shp


def main() -> int:
    if not REFERENCE.exists():
        raise SystemExit(f"missing {REFERENCE} - run scripts/build_terrain.py first")

    shp = extract()
    print(f"rasterising {shp.name} onto the grid of {REFERENCE.name} ...", flush=True)
    stats = rasterise(shp, REFERENCE, OUT_TIF)

    covered = stats["cells_covered"]
    cells = stats["cells"]
    lines = []
    a = lines.append
    a("# Superficial deposits, burned to the Agder grid\n")
    a("Generated by `scripts/build_losmasser.py`. No model fitted.\n")
    a(f"`{OUT_TIF.relative_to(ROOT)}` - uint8, 32 m, EPSG:25833, aligned "
      f"cell-for-cell with `{REFERENCE.name}`.\n")
    a(f"{stats['polygons']:,} polygons in, {stats['polygons_burned']:,} burned. "
      f"{covered:,} of {cells:,} cells carry a deposit class "
      f"({stats['coverage_pct']:.1f}% of the raster rectangle).\n")
    a("The rectangle includes sea and the parts of neighbouring counties that")
    a("fall inside Agder's bounding box, so this percentage is a floor on land")
    a("coverage rather than a measure of it. What matters for the model is the")
    a("share of *point* locations answered for, which is reported by")
    a("`scripts/check_raster_coverage.py` against the actual point sets.\n")

    a("## Cells per group\n")
    a("| group | cells | % of covered |")
    a("|---|---|---|")
    for name in LABELS.values():
        n = stats["cells_by_group"][name]
        pct = 100.0 * n / covered if covered else 0.0
        a(f"| {name} | {n:,} | {pct:.1f}% |")
    a("")

    if stats["unmapped_jordart"]:
        a("## Jordart codes the grouping does not cover\n")
        a("These became nodata rather than being absorbed into a residual")
        a("class. A non-empty table means the grouping has fallen behind the")
        a("source and must be revisited before this layer is read.\n")
        a("| jordart | polygons |")
        a("|---|---|")
        for code, n in sorted(stats["unmapped_jordart"].items()):
            a(f"| {code} | {n:,} |")
        a("")
    else:
        a("Every `jordart` code present in the extract falls into a registered")
        a("group; nothing was silently dropped.\n")

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"written: {OUT_TIF.relative_to(ROOT)}")
    print(f"written: {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
