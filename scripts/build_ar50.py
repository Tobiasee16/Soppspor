"""Burn AR50 land cover onto the Agder terrain grid.

    python scripts/build_ar50.py

The open stand-in for FKB-AR5, which is Norge digitalt restricted. See
`src/ingest/ar50.py` for what that costs and what it buys, and data/SOURCES.md
for the licence finding.
"""
from __future__ import annotations

import pathlib
import sys
import zipfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

from src.ingest.ar50 import LABELS, NORWEGIAN, rasterise

ROOT = pathlib.Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "ar50"
EXTRACT = ROOT / "data" / "interim" / "ar50"
REFERENCE = ROOT / "data" / "interim" / "terrain_agder_32m.tif"
OUT_TIF = ROOT / "data" / "interim" / "ar50_agder_32m.tif"
OUT_MD = ROOT / "data" / "processed" / "ar50.md"

ZIP_NAME = "42_25832_ar50_gml.zip"
GML_NAME = "42_25832_ar50_gml.gml"


def extract() -> pathlib.Path:
    gml = EXTRACT / GML_NAME
    if gml.exists():
        return gml
    archive = RAW / ZIP_NAME
    if not archive.exists():
        raise SystemExit(f"missing {archive} - run scripts/download_rasters.py --only ar50")
    EXTRACT.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive) as z:
        z.extractall(EXTRACT)
    if not gml.exists():
        raise SystemExit(f"{ZIP_NAME} did not contain {GML_NAME}")
    return gml


def main() -> int:
    if not REFERENCE.exists():
        raise SystemExit(f"missing {REFERENCE} - run scripts/build_terrain.py first")
    gml = extract()
    print(f"reprojecting and rasterising {gml.name} ...", flush=True)
    s = rasterise(gml, REFERENCE, OUT_TIF)

    covered = s["cells_covered"]
    w = []
    a = w.append
    a("# AR50 land cover, burned to the Agder grid\n")
    a("Generated by `scripts/build_ar50.py`. No model fitted.\n")
    a(f"`{OUT_TIF.relative_to(ROOT)}` - uint8, 32 m, EPSG:25833, aligned "
      f"cell-for-cell with `{REFERENCE.name}`.\n")
    a("## Why AR50 and not AR5\n")
    a("CLAUDE.md's data table asks for NIBIO AR5 at 1:5,000. Geonorge's "
      "catalogue reports FKB-AR5 as `AccessIsRestricted: true`, "
      "`DataAccess: \"Norge digitalt begrenset\"`, under Geovekst terms. That "
      "is a **licence** restriction, not a missing technical route: there is "
      "nothing to engineer around, and engineering around it would mean using "
      "data we are not licensed for. AR50 is the same agency's generalised "
      "product, published as open data under NLOD.\n")
    a("The cost is a factor of ten in scale. AR50's minimum mapping unit is far "
      "larger, so small clearings, narrow bogs and field edges are not in it. "
      "Read it as *roughly what kind of ground is this*, never as a boundary.\n")
    if s["reprojected"]:
        a(f"Reprojected {s['source_crs']} -> {s['target_crs']} on ingest. AR50 is "
          "offered for Agder only in 4258 and 25832, because Agder really does "
          "fall in UTM zone 32 - the same zone-32 trap CLAUDE.md's CRS note "
          "warns about, arriving from a different direction.\n")

    a("## Cells per class\n")
    a(f"{s['polygons']:,} polygons in, {s['polygons_burned']:,} burned, "
      f"{s['not_mapped_polygons']:,} left as nodata because AR50 records them "
      "as *ikke kartlagt* - an absence of information, not a kind of ground.\n")
    a(f"{covered:,} of {s['cells']:,} cells carry a class "
      f"({s['coverage_pct']:.1f}% of the raster rectangle, which includes sea "
      "and neighbouring counties).\n")
    a("| class | norsk | cells | % of covered |")
    a("|---|---|---|---|")
    for code, name in LABELS.items():
        n = s["cells_by_group"][name]
        pct = 100.0 * n / covered if covered else 0.0
        a(f"| {name} | {NORWEGIAN[code]} | {n:,} | {pct:.1f}% |")
    a("")

    if s["unmapped_arealtype"]:
        a("## Arealtype codes the grouping does not name\n")
        a("A non-empty table means AR50 has changed and the grouping in "
          "`src/ingest/ar50.py` has fallen behind it.\n")
        a("| arealtype | polygons |")
        a("|---|---|")
        for code, n in sorted(s["unmapped_arealtype"].items()):
            a(f"| {code} | {n:,} |")
        a("")
    else:
        a("Every `arealtype` code in the delivery is either a named class or "
          "*ikke kartlagt*; nothing was silently dropped.\n")

    a("## The check that mattered\n")
    a("AR50 codes agriculture as `20`. AR5 uses `21`/`22`/`23` for agriculture "
      "and puts transport at `12`. Reading 20 the AR5 way would have "
      "relabelled every agricultural polygon in Agder as roads, and nothing "
      "would have failed. It was verified against the delivered data instead: "
      "every polygon with arealtype 20 carries a `jordbruk` code (24 fulldyrka, "
      "25 innmarksbeite) and no other arealtype does.\n")

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(w), encoding="utf-8")
    print("\n".join(w))
    print(f"written: {OUT_TIF.relative_to(ROOT)}")
    print(f"written: {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
