"""Does spatial blocking leave usable folds on the real record counts?

The open question raised when the counts came in. Blocks large enough to break
autocorrelation are also large enough to swallow a small dataset: at some block
size, every fold ends up with too few presences to be graded on, and the
fold-level numbers become noise dressed as a result.

Answers it directly, per species, at several block sizes. No model involved.

    python scripts/check_cv_blocks.py
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

import json

import yaml

from src.features.thin import thin
from src.geometry import Boundary
from src.ingest import artskart
from src.validate.blocks import assign_blocks, fold_adequacy_warnings, make_folds

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "processed" / "cv_block_adequacy.md"
BLOCK_SIZES = [5000, 7500, 10000]
MIN_PRESENCES = 10


def main():
    area = yaml.safe_load((ROOT / "config" / "study_area.yaml").read_text(encoding="utf-8"))
    spp = yaml.safe_load((ROOT / "config" / "species.yaml").read_text(encoding="utf-8"))
    n_folds = area["spatial_cv"]["n_folds"]
    thin_m = area["reporting_thinning_m"]
    max_prec = area["max_coordinate_precision_m"]

    extents = {}
    for slot in ("training_extent", "prediction_extent"):
        path = ROOT / area[slot]["boundary_file"]
        if not path.exists():
            raise SystemExit(
                f"missing {path}. Run scripts/report_counts.py first to fetch boundaries."
            )
        fc = json.loads(path.read_text(encoding="utf-8"))
        extents[slot] = (area[slot]["name"], Boundary(fc["features"][0]["geometry"]))

    lines = []
    w = lines.append
    w("# Spatial CV block adequacy")
    w("")
    w("Generated by `scripts/check_cv_blocks.py`. No model fitted.")
    w("")
    w(f"Presences are thinned to {thin_m} m and filtered to stated coordinate")
    w(f"precision <= {max_prec} m. Folds: {n_folds}. A fold holding fewer than")
    w(f"{MIN_PRESENCES} test presences cannot be graded meaningfully on its own.")
    w("")

    any_problem = False
    for slot, (name, boundary) in extents.items():
        w(f"## {name}")
        w("")
        w("| Species | block | distinct blocks | presences per fold | min | verdict |")
        w("|---|---|---|---|---|---|")
        for sp in spp["species"]:
            raw = ROOT / "data" / "raw" / "artskart" / f"{sp['key']}.json"
            if not raw.exists():
                raise SystemExit(f"missing {raw}. Run scripts/report_counts.py first.")
            pts = artskart.usable_points(artskart.load(raw))
            pts = [p for p in pts if (p["east"], p["north"]) in boundary]
            pts = [p for p in pts if p["precision_m"] is not None and p["precision_m"] <= max_prec]
            pts = thin(pts, thin_m)
            coords = [(p["east"], p["north"]) for p in pts]
            y = [1] * len(coords)

            for bs in BLOCK_SIZES:
                blocks = assign_blocks(coords, bs)
                n_blocks = len(set(blocks))
                if n_blocks < n_folds:
                    w(f"| *{sp['scientific_name']}* | {bs} m | {n_blocks} | - | - | "
                      f"**TOO FEW BLOCKS** |")
                    any_problem = True
                    continue
                fa = make_folds(blocks, y, n_folds=n_folds, block_size_m=bs, seed=0)
                warns = fold_adequacy_warnings(fa, min_presences=MIN_PRESENCES)
                verdict = "OK" if not warns else "**thin**"
                if warns:
                    any_problem = True
                per_fold = ", ".join(str(n) for n in fa.presences_per_fold)
                w(f"| *{sp['scientific_name']}* | {bs} m | {n_blocks} | {per_fold} | "
                  f"{fa.min_presences} | {verdict} |")
        w("")

    w("## Reading")
    w("")
    if any_problem:
        w("At least one species/extent/block-size combination leaves a fold too thin")
        w("to grade. Those cells are marked. Do not quote a per-fold number from them;")
        w("the pooled figure across folds is still usable, with a wide interval.")
    else:
        w("Every combination leaves enough presences per fold to be graded.")
    w("")
    w("Note that these counts are presences only. Background points are not yet")
    w("built, so a fold that looks adequate here could still be unusable once")
    w("target-group background sampling is in place.")
    w("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"written: {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
