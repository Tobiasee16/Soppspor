"""First task before any modelling: thinned record counts per species, per extent.

CLAUDE.md: "If a species falls short even at the Agder extent, tell us rather
than proceeding with a model that cannot support conclusions."

This script does not model anything and must never be made to. It downloads
occurrence records, clips them to the two extents, and reports how many survive
spatial thinning. That is all.

Usage:
    python scripts/report_counts.py [--refresh]
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

import yaml

# The Windows console is cp1252 by default and will raise on any character
# outside it. The report file itself is always written as UTF-8; this only
# affects what gets echoed to the terminal.
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

from src.features.thin import thin
from src.geometry import Boundary
from src.ingest import artskart, boundaries
from src import species as species_cfg

ROOT = pathlib.Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "artskart"
OUT = ROOT / "data" / "processed" / "record_counts.md"

# Rough guidance from the presence-only SDM literature, and the number CLAUDE.md
# names. Not a hard threshold, but below it we should say so out loud.
MIN_RECORDS_ADVISORY = 50


def load_config():
    with open(ROOT / "config" / "study_area.yaml", encoding="utf-8") as f:
        area = yaml.safe_load(f)
    with open(ROOT / "config" / "species.yaml", encoding="utf-8") as f:
        spp = yaml.safe_load(f)
    return area, spp


def get_boundaries(area, refresh: bool):
    out = {}
    for slot in ("training_extent", "prediction_extent"):
        cfg = area[slot]
        dest = ROOT / cfg["boundary_file"]
        if refresh or not dest.exists():
            print(f"  fetching boundary: {cfg['name']}")
            fc = boundaries.fetch(cfg["boundary_url"], dest)
        else:
            fc = json.loads(dest.read_text(encoding="utf-8"))
        declared = fc.get("crs_declared_by_source")
        if declared and "25833" not in str(declared):
            raise RuntimeError(
                f"{cfg['name']} boundary came back as {declared}, expected EPSG:25833. "
                f"Stop and check the Geonorge utkoordsys parameter."
            )
        out[slot] = Boundary(fc["features"][0]["geometry"], name=cfg["name"])
        print(f"  {cfg['name']}: bbox {tuple(round(v) for v in out[slot].bbox)}")
    return out


def get_records(sp, refresh: bool):
    dest = RAW / f"{sp['key']}.json"
    if refresh or not dest.exists():
        print(f"  downloading {sp['scientific_name']} (taxon {sp['artskart_taxon_id']}) ...")
        payload = artskart.download_taxon(sp["artskart_taxon_id"], dest)
        print(f"    {payload['records_downloaded']} records")
    return artskart.usable_points(artskart.load(dest))


def summarise(points, boundary, distances, max_precision):
    """Counts inside one extent, at each thinning distance, two precision regimes."""
    inside = [p for p in points if (p["east"], p["north"]) in boundary]
    precise = [p for p in inside if p["precision_m"] is not None and p["precision_m"] <= max_precision]
    return {
        "n_inside": len(inside),
        "n_precise": len(precise),
        "all": {d: len(thin(inside, d)) for d in distances},
        "precise": {d: len(thin(precise, d)) for d in distances},
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true", help="re-download even if cached")
    args = ap.parse_args()

    area, spp = load_config()
    distances = area["thinning_distances_m"]
    max_prec = area["max_coordinate_precision_m"]
    report_d = area["reporting_thinning_m"]

    print("Boundaries (Kartverket / Geonorge, EPSG:25833):")
    bnds = get_boundaries(area, args.refresh)

    print("\nOccurrence records (Artskart, national pull, clipped client-side):")
    results = {}
    for sp in species_cfg.modelled(spp):
        pts = get_records(sp, args.refresh)
        results[sp["key"]] = {
            "sp": sp,
            "n_national_usable": len(pts),
            "training": summarise(pts, bnds["training_extent"], distances, max_prec),
            "prediction": summarise(pts, bnds["prediction_extent"], distances, max_prec),
        }

    lines = []
    w = lines.append
    w("# Thinned record counts")
    w("")
    w("Generated by `scripts/report_counts.py`. No model has been fitted. These are")
    w("counts only, produced to decide whether Phase 0 can support conclusions at all.")
    w("")
    w(f"- Source: Artskart `observations/list`, national pull per taxon, clipped client-side.")
    w(f"- Extents: **{area['training_extent']['name']}** (training) and "
      f"**{area['prediction_extent']['name']}** (prediction/validation). Kept distinct.")
    w(f"- Coordinates: source projection EPSG:32633, treated as EPSG:25833 "
      f"(sub-metre difference, immaterial at these thinning distances).")
    w(f"- \"Precise\" = stated coordinate precision <= {max_prec} m. Records with no")
    w("  stated precision are excluded from the precise columns, not assumed good.")
    w("")

    for label, slot in (("Training extent - " + area["training_extent"]["name"], "training"),
                        ("Prediction extent - " + area["prediction_extent"]["name"], "prediction")):
        w(f"## {label}")
        w("")
        head = "| Species | in extent | " + " | ".join(f"thin {d} m" for d in distances) + " |"
        w(head)
        w("|" + "---|" * (2 + len(distances)))
        for key, r in results.items():
            s = r[slot]
            cells = " | ".join(str(s["all"][d]) for d in distances)
            w(f"| *{r['sp']['scientific_name']}* ({r['sp']['vernacular_no']}) | {s['n_inside']} | {cells} |")
        w("")
        w(f"Precision-filtered (<= {max_prec} m):")
        w("")
        w(head.replace("in extent", "precise"))
        w("|" + "---|" * (2 + len(distances)))
        for key, r in results.items():
            s = r[slot]
            cells = " | ".join(str(s["precise"][d]) for d in distances)
            w(f"| *{r['sp']['scientific_name']}* | {s['n_precise']} | {cells} |")
        w("")

    w("## Verdict")
    w("")
    w(f"Advisory minimum for a presence-only model: **{MIN_RECORDS_ADVISORY} thinned records**")
    w(f"(at the {report_d} m reporting distance, training extent).")
    w("")
    for key, r in results.items():
        n_all = r["training"]["all"][report_d]
        n_prec = r["training"]["precise"][report_d]
        verdict = "OK" if n_prec >= MIN_RECORDS_ADVISORY else (
            "OK only without the precision filter" if n_all >= MIN_RECORDS_ADVISORY else "SHORT")
        w(f"- *{r['sp']['scientific_name']}*: {n_all} thinned "
          f"({n_prec} precision-filtered) -> **{verdict}**")
    w("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n" + "\n".join(lines))
    print(f"\nwritten: {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
