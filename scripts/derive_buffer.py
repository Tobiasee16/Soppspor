"""Derive the CV exclusion buffer from the real occurrence data.

The buffer was provisionally set to 4 km against a synthetic cluster scale of
1.2 km sd. That is evidence about the self-test and nothing about Norwegian
fungal records. This script replaces it with measurement.

It does not produce the number it was written to produce. The pair correlation
function of these records declines smoothly from g = 8.6 at 1 km to 1.1 at
30 km without ever flattening, so there is no distance at which spatial
dependence stops and therefore no "autocorrelation range" to set the buffer to.
The buffer is consequently a trade-off - leakage against training data - and
this script reports both sides of it rather than asserting a threshold.

Two nulls are used, and the contrast between them is the point:

* uniform - "are these records clumped?" Yes, at every scale, mostly because
  recording effort is concentrated near settlements.
* intensity - "are they clumped beyond their own regional density?" Also yes.
  This is the one the buffer must answer to, because the regional gradient is
  what blocking and target-group background sampling exist to handle.

    python scripts/derive_buffer.py
"""
from __future__ import annotations

import json
import math
import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

import yaml

from src.features.thin import thin
from src.geometry import Boundary
from src.ingest import artskart
from src.validate.autocorrelation import (
    IntensitySampler,
    UniformSampler,
    decay_range,
    excess_remaining,
    far_field_baseline,
    far_field_reached,
    max_reliable_r,
    nearest_neighbour_distances,
    pair_correlation,
    percentile,
)
from src.validate.blocks import assign_blocks, make_folds
from src.validate.harness import buffer_cost

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "processed" / "autocorrelation_range.md"

BIN_M = 1000.0
N_SIM = 39
SAMPLER_CELL_M = 2000.0
BANDWIDTHS_M = [20000.0, 30000.0, 40000.0]
REPORTING_BANDWIDTH_M = 30000.0
SEED = 0
CANDIDATE_BUFFERS = [0.0, 1000.0, 2000.0, 3000.0, 4000.0, 5000.0, 6000.0, 7500.0]
# The buffer is bounded by the data budget, not by a statistic: no practical
# distance removes the dependence, so the binding constraint is how few training
# presences the thinnest fold can be left with.
MIN_RETENTION = 0.85


def presences(raw_path, boundary, max_prec, thin_m):
    pts = artskart.usable_points(artskart.load(raw_path))
    pts = [p for p in pts if (p["east"], p["north"]) in boundary]
    pts = [p for p in pts if p["precision_m"] is not None and p["precision_m"] <= max_prec]
    return [(p["east"], p["north"]) for p in thin(pts, thin_m)]


def fmt_m(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "**none found**"
    return f"{v:.0f} m"


def main():
    area = yaml.safe_load((ROOT / "config" / "study_area.yaml").read_text(encoding="utf-8"))
    spp = yaml.safe_load((ROOT / "config" / "species.yaml").read_text(encoding="utf-8"))
    max_prec = area["max_coordinate_precision_m"]
    thin_m = area["reporting_thinning_m"]
    n_folds = area["spatial_cv"]["n_folds"]
    block_m = area["spatial_cv"]["block_size_m"]
    cv_slot = area["spatial_cv"]["cv_extent"]

    path = ROOT / area[cv_slot]["boundary_file"]
    if not path.exists():
        raise SystemExit(f"missing {path}. Run scripts/report_counts.py first.")
    fc = json.loads(path.read_text(encoding="utf-8"))
    boundary = Boundary(fc["features"][0]["geometry"], name=area[cv_slot]["name"])
    max_r = max_reliable_r(boundary)
    print(f"rasterising {boundary.name} at {SAMPLER_CELL_M:.0f} m ...", flush=True)
    uniform = UniformSampler(boundary, cell_m=SAMPLER_CELL_M)
    print(f"  {len(uniform.cells)} cells inside; estimating g out to {max_r/1000:.0f} km",
          flush=True)

    sets = {}
    for sp in spp["species"]:
        raw = ROOT / "data" / "raw" / "artskart" / f"{sp['key']}.json"
        if not raw.exists():
            raise SystemExit(f"missing {raw}. Run scripts/report_counts.py first.")
        sets[sp["key"]] = presences(raw, boundary, max_prec, thin_m)

    lines = []
    w = lines.append
    w("# Spatial dependence in the occurrence records, and what it means for the buffer")
    w("")
    w("Generated by `scripts/derive_buffer.py`. No model fitted.")
    w("")
    w("**Headline: there is no autocorrelation range in these records to set the")
    w("buffer from.** Spatial dependence declines smoothly across every distance")
    w("we can measure and never reaches a floor. The buffer is therefore a")
    w("trade-off between leakage and training data, chosen and declared, not a")
    w("threshold derived from the data. Both sides are quantified below.")
    w("")
    w(f"All figures: {area[cv_slot]['name']}, records thinned to {thin_m} m and")
    w(f"filtered to stated precision <= {max_prec} m - the exact set blocked CV will")
    w(f"run on. g(r) in {BIN_M:.0f} m bins out to {max_r/1000:.0f} km ({N_SIM} simulations).")
    w("")
    w("The prediction extent is not analysed here. It is held out and evaluated")
    w("once rather than cross-validated, so no exclusion buffer applies to it.")
    w("")

    # --- 1. uniform null -------------------------------------------------------
    w("## 1. Against a uniform null: clumped at every scale")
    w("")
    w("| Species | n | g at 1 km | g at 10 km | g at 20 km | far-field g | levelled off? |")
    w("|---|---|---|---|---|---|---|")
    for sp in spp["species"]:
        coords = sets[sp["key"]]
        print(f"  uniform null: {sp['key']} n={len(coords)}", flush=True)
        pc = pair_correlation(coords, uniform, max_r_m=max_r, bin_m=BIN_M,
                              n_sim=N_SIM, seed=SEED)
        gk = lambda km: pc.g[min(int(km * 1000 // BIN_M), len(pc.g) - 1)]  # noqa: E731
        w(f"| *{sp['scientific_name']}* | {len(coords)} | {gk(1):.1f} | {gk(10):.1f} | "
          f"{gk(20):.1f} | {far_field_baseline(pc):.2f} | "
          f"{'yes' if far_field_reached(pc) else '**no**'} |")
    w("")
    w("A far-field g near 1.9 means that at 25-30 km apart, two records are still")
    w("almost twice as likely to co-occur as chance. That is the regional")
    w("concentration of recording effort - more records near Kristiansand and")
    w("Arendal than in the inland valleys - and it is not what an exclusion buffer")
    w("can or should fix. Hard constraint 3 (target-group background sampling) is")
    w("the instrument for it.")
    w("")

    # --- 2. intensity null -----------------------------------------------------
    w("## 2. Against the records' own regional density: still no floor")
    w("")
    w("The null now carries the regional density, smoothed with a Gaussian kernel,")
    w("so only clumping finer than the kernel counts. If local clumping had a")
    w("range, g would fall to 1 and stay there. It does not.")
    w("")
    w("| Species | kernel | g at 1 km | 4 km | 10 km | 20 km | far-field g | levelled off? | range |")
    w("|---|---|---|---|---|---|---|---|---|")
    pcs = {}
    for sp in spp["species"]:
        coords = sets[sp["key"]]
        for bw in BANDWIDTHS_M:
            print(f"  intensity null: {sp['key']} bw={bw/1000:.0f}km", flush=True)
            pc = pair_correlation(
                coords,
                IntensitySampler(boundary, coords, cell_m=SAMPLER_CELL_M, bandwidth_m=bw),
                max_r_m=max_r, bin_m=BIN_M, n_sim=N_SIM, seed=SEED,
            )
            if bw == REPORTING_BANDWIDTH_M:
                pcs[sp["key"]] = pc
            gk = lambda km: pc.g[min(int(km * 1000 // BIN_M), len(pc.g) - 1)]  # noqa: E731
            w(f"| *{sp['scientific_name']}* | {bw/1000:.0f} km | {gk(1):.1f} | {gk(4):.1f} | "
              f"{gk(10):.1f} | {gk(20):.1f} | {far_field_baseline(pc):.2f} | "
              f"{'yes' if far_field_reached(pc) else '**no**'} | {fmt_m(decay_range(pc))} |")
    w("")
    w("Every species, at every kernel width, is still declining at the outer edge")
    w("of what can be estimated. The estimator refuses to return a range rather")
    w("than reporting the level it happens to have reached, which would be an")
    w("artefact of where we stopped measuring.")
    w("")
    w("The result is insensitive to the kernel width, which is the main thing that")
    w("could have driven it. It is a property of the records, not of the method.")
    w("")

    # --- 3. the trade-off ------------------------------------------------------
    w("## 3. What each buffer buys and what it costs")
    w("")
    w(f"Excess remaining: the share of short-range clumping still present at that")
    w(f"separation, against the {REPORTING_BANDWIDTH_M/1000:.0f} km kernel null. Since the curve")
    w("never flattens, the far-field level used is an upper bound on the true one,")
    w("so these are floors on the leakage, not estimates of it.")
    w("")
    w(f"Retention: share of training presences surviving the buffer, averaged over")
    w(f"{n_folds} folds at {block_m:.0f} m blocks, with the thinnest fold in brackets.")
    w("Presence-side only - target-group background does not exist yet and will")
    w("add its own cost.")
    w("")
    w("| Buffer | " + " | ".join(
        f"{sp['scientific_name'].split()[0][:5]}. excess / retention" for sp in spp["species"]
    ) + " |")
    w("|---" * (len(spp["species"]) + 1) + "|")

    costs = {}
    for sp in spp["species"]:
        coords = sets[sp["key"]]
        y = [1] * len(coords)
        blocks = assign_blocks(coords, block_m)
        fa = make_folds(blocks, y, n_folds=n_folds, block_size_m=block_m, seed=0)
        costs[sp["key"]] = {
            b: buffer_cost(coords, y, fa.fold_of_point, n_folds, b)
            for b in CANDIDATE_BUFFERS
        }

    for b in CANDIDATE_BUFFERS:
        cells = []
        for sp in spp["species"]:
            ex = excess_remaining(pcs[sp["key"]], b) if b > 0 else 1.0
            c = costs[sp["key"]][b]
            cells.append(f"{ex:.0%} / {c['presence_retention']:.0%} "
                         f"({c['min_train_presences']})")
        w(f"| {b:.0f} m | " + " | ".join(cells) + " |")
    w("")

    # --- 4. choice -------------------------------------------------------------
    affordable = [
        b for b in CANDIDATE_BUFFERS
        if min(costs[sp["key"]][b]["presence_retention"] for sp in spp["species"])
        >= MIN_RETENTION
    ]
    chosen = max(affordable) if affordable else 0.0
    worst_excess = max(excess_remaining(pcs[sp["key"]], chosen) for sp in spp["species"])

    w("## 4. The choice, and what it does not fix")
    w("")
    w(f"**buffer_m = {chosen:.0f}.** Chosen as the largest buffer that still leaves")
    w(f"{MIN_RETENTION:.0%} of training presences in the worst species, because with no")
    w("range in the data the binding constraint is the data budget rather than any")
    w("property of the point pattern. It is a declared trade-off. It is not the")
    w("autocorrelation range, and it must not be described as one.")
    w("")
    w(f"At this buffer at least **{worst_excess:.0%} of the short-range spatial")
    w("dependence remains** in the worst species. Blocked CV on this data is")
    w("therefore still optimistic. Three consequences follow, and they are not")
    w("optional:")
    w("")
    w("1. **The null control becomes the load-bearing check, not the buffer.** Hard")
    w("   constraint 5 already requires the synthetic null in every run. Given")
    w("   residual leakage of this size, a null that scores above 0.5 is the")
    w("   expected failure, and it is the number to read first.")
    w("2. **The blocked-versus-random gap must be reported for every species.** The")
    w("   absolute blocked figure carries known contamination; the gap between the")
    w("   two schemes is the more honest quantity and the harness returns both.")
    w("3. **A blocked AUC modestly above 0.5 is not evidence of ecology.** The")
    w("   predicted ordering across the three species, and the null sitting at")
    w("   0.5, remain the falsification test. A single species' number does not.")
    w("")
    w("### What would settle this properly")
    w("")
    w("Leakage can be measured directly rather than bounded, but not yet: it needs")
    w("target-group background, which does not exist. With it, the synthetic null")
    w("species can be run at a sweep of buffers, and the buffer chosen where the")
    w("null returns to 0.5 on real geography. That is a measurement of the thing")
    w("itself instead of a proxy for it, and it should replace this choice.")
    w("")

    # --- 5. descriptive ---------------------------------------------------------
    w("### Nearest-neighbour distances, for reference")
    w("")
    w("| Species | 10th | median | 90th |")
    w("|---|---|---|---|")
    for sp in spp["species"]:
        nn = nearest_neighbour_distances(sets[sp["key"]])
        w(f"| *{sp['scientific_name']}* | {percentile(nn, 10):.0f} m | "
          f"{percentile(nn, 50):.0f} m | {percentile(nn, 90):.0f} m |")
    w("")
    w("After thinning to a 1 km grid the median record still has a neighbour")
    w("inside 1.3 km, because thinning is by grid cell and two records in")
    w("adjoining cells can be metres apart.")
    w("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print()
    print("\n".join(lines))
    print(f"written: {OUT.relative_to(ROOT)}")
    print(f"\nCHOSEN buffer_m: {chosen:.0f} (residual excess >= {worst_excess:.0%})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
